const rand = (min: number, max: number) => Math.floor(Math.random() * (max - min + 1)) + min;

function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function generateUniqueName(usedNames: Set<string>): string {
  let attempts = 0;
  while (attempts < 5000) {
    const first = pickRandom(FIRST_NAMES);
    const last = pickRandom(LAST_NAMES);
    const full = `${first} ${last}`;
    if (!usedNames.has(full)) {
      usedNames.add(full);
      return full;
    }
    attempts++;
  }
  const fallback = `Player-${usedNames.size + 1}`;
  usedNames.add(fallback);
  return fallback;
}

export function generateUniqueTeamName(usedTeamNames: Set<string>, series: "A" | "B"): string {
  const prefixes = series === "A" ? TEAM_PREFIXES_A : TEAM_PREFIXES_B;
  let attempts = 0;
  while (attempts < 5000) {
    const prefix = pickRandom(prefixes);
    const middle = pickRandom(TEAM_MIDDLES);
    const mascot = pickRandom(TEAM_MASCOTS);
    const full = `${prefix} ${middle} ${mascot}`;
    if (!usedTeamNames.has(full)) {
      usedTeamNames.add(full);
      return full;
    }
    attempts++;
  }
  const fallback = `Team-${usedTeamNames.size + 1}`;
  usedTeamNames.add(fallback);
  return fallback;
}
